// Regenerates src/lib/pdf/font-data.ts from the subset TTFs in assets/fonts.
// Fonts are embedded as base64 so PDFs never depend on files existing at runtime
// (on Hostinger the server's working directory / shipped files are not guaranteed).
//
// To change the character set, re-subset the full Noto Sans fonts with fonttools, e.g.:
//   pyftsubset NotoSans-Regular.ttf --unicodes="U+0020-007E,U+00A0-017F,U+0192,U+02C6-02DC,U+2010-2027,U+2030-203A,U+20A0-20C0,U+2122,U+2190-2193,U+2212,U+FFFD" \
//     --layout-features="kern,liga" --output-file=assets/fonts/NotoSans-Regular-subset.ttf
// then run:  node scripts/embed-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";

const b64 = (f) => readFileSync(new URL(`../assets/fonts/${f}`, import.meta.url)).toString("base64");

const out = `// GENERATED by scripts/embed-fonts.mjs — do not edit by hand.
// Noto Sans (SIL Open Font License 1.1, see assets/fonts/OFL.txt), subset to Latin + punctuation + currency (incl. ₹).
export const NOTO_SANS_REGULAR = "data:font/ttf;base64,${b64("NotoSans-Regular-subset.ttf")}";
export const NOTO_SANS_BOLD = "data:font/ttf;base64,${b64("NotoSans-Bold-subset.ttf")}";
`;
writeFileSync(new URL("../src/lib/pdf/font-data.ts", import.meta.url), out);
console.log(`Wrote src/lib/pdf/font-data.ts (${(out.length / 1024).toFixed(0)} KB)`);
