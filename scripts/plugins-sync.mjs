// Generates src/plugins/registry.generated.ts: a static import of every code plugin folder
// (src/plugins/<id>/index.ts[x]). Static imports let the bundler include plugins in the build.
// Runs automatically before `dev`, `build` and tests; run by hand with `npm run plugins:sync`.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../src/plugins/", import.meta.url));
const out = join(root, "registry.generated.ts");

const folders = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_") && !d.name.startsWith("."))
  .map((d) => d.name)
  .filter((name) => {
    const ok = existsSync(join(root, name, "index.ts")) || existsSync(join(root, name, "index.tsx"));
    if (!ok) console.warn(`[plugins] skipped src/plugins/${name}: no index.ts`);
    if (ok && !/^[a-z][a-z0-9-]{1,40}[a-z0-9]$/.test(name)) {
      console.error(`[plugins] src/plugins/${name}: folder name must be the plugin id (lowercase letters, digits, dashes)`);
      process.exit(1);
    }
    return ok;
  })
  .sort();

const ident = (name) => "p_" + name.replace(/-/g, "_");
const body = `// GENERATED by scripts/plugins-sync.mjs: do not edit. Lists every code plugin in src/plugins.
import type { PluginDefinition } from "@/lib/plugins/sdk";
${folders.map((f) => `import ${ident(f)} from "./${f}";`).join("\n")}

export const CODE_PLUGINS: Array<{ folder: string; definition: PluginDefinition }> = [
${folders.map((f) => `  { folder: "${f}", definition: ${ident(f)} },`).join("\n")}
];
`;

const previous = existsSync(out) ? readFileSync(out, "utf8") : "";
if (previous !== body) {
  writeFileSync(out, body);
  console.log(`[plugins] registry updated: ${folders.length} code plugin(s)${folders.length ? `: ${folders.join(", ")}` : ""}`);
}
